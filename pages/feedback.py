import logging
import pandas as pd
import numpy as np
import dash_bootstrap_components as dbc
from dash import dcc, html, Input, Output
import plotly.express as px
import plotly.graph_objs as go

def layout():
    # For demonstration, create dummy forecast data for the next 6 months.
    months = pd.date_range(start=pd.Timestamp.today(), periods=6, freq='MS')
    # Simulate predicted crime counts with some trend and noise.
    np.random.seed(42)
    base = 1000
    trend = np.linspace(0, 100, 6)
    noise = np.random.randint(-50, 50, size=6)
    predictions = base + trend + noise
    df_forecast = pd.DataFrame({
        'Month': months,
        'Predicted Crime Count': predictions
    })

    forecast_chart = dcc.Graph(
        id="prediction-chart",
        figure=px.line(
            df_forecast,
            x="Month",
            y="Predicted Crime Count",
            title="Crime Forecast for Next 6 Months",
            markers=True
        ).update_layout(transition={"duration": 500}, margin={"r":0,"t":40,"l":0,"b":0})
    )

    return dbc.Container(
        fluid=True,
        children=[
            html.H1("Crime Prediction", style={'textAlign': 'center', 'marginBottom': '20px'}),
            html.P(
                "This page shows a forecast of crime counts for the upcoming months. "
                "In a full implementation, these predictions would be generated by a trained machine learning model.",
                style={'textAlign': 'center'}
            ),
            forecast_chart,
            html.Div(id="prediction-details", style={'textAlign': 'center', 'marginTop': '20px'})
        ]
    )

def register_callbacks(app):
    # Optionally, add callbacks here if you want interactivity (e.g., adjusting forecast parameters)
    @app.callback(
        Output("prediction-details", "children"),
        [Input("prediction-chart", "clickData")]
    )
    def display_forecast_details(clickData):
        if clickData:
            point = clickData['points'][0]
            month = point['x']
            count = point['y']
            return f"Forecast for {month}: {count:.0f} crimes predicted."
        return "Click on a data point in the forecast chart for details."


